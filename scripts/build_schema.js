// Writes supabase/schema.sql from framework.json. Run: node scripts/build_schema.js
'use strict';
const fs = require('fs');
const path = require('path');
const { TABLES } = require('../server/schema');

const L = [];
L.push('-- Life in Design Coach · Supabase schema');
L.push('-- Generated by scripts/build_schema.js from framework.json. Do not edit by hand; edit framework.json and rebuild.');
L.push('-- Safe to run more than once: it creates what is missing and replaces the functions, policies and trigger.');
L.push('-- Supabase applies it from supabase/migrations/ through the GitHub integration; it can also be pasted into the SQL Editor.');
L.push('');
L.push('-- Every value the coaching engine stores is text (as in the Google Sheet), so the engine runs unchanged.');
L.push('-- Row ids and user ids are uuid; seq keeps rows in the order they were written.');
L.push('');

for (const t of Object.values(TABLES)) {
  const singleUuidPk = t.pk.length === 1 && t.pk[0] !== 'user_id';
  const defs = t.columns.map((c) => {
    if (c.col === 'user_id') return `  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade`;
    if (singleUuidPk && c.col === t.pk[0]) return `  ${c.col} uuid not null`;
    return `  ${c.col} text not null default ''`;
  });
  defs.push(`  seq bigint generated always as identity`);
  defs.push(`  inserted_at timestamptz not null default now()`);
  defs.push(`  primary key (${t.pk.join(', ')})`);
  L.push(`-- ${t.sheet}`);
  L.push(`create table if not exists public.${t.table} (\n${defs.join(',\n')}\n);`);
  for (const c of t.columns) {
    // Columns added to framework.json later are added here without touching existing data.
    if (c.col === 'user_id' || (singleUuidPk && c.col === t.pk[0])) continue;
    L.push(`alter table public.${t.table} add column if not exists ${c.col} text not null default '';`);
  }
  L.push(`create index if not exists ${t.table}_user_seq on public.${t.table} (user_id, seq);`);
  if (t.table === 'messages') L.push(`create index if not exists messages_user_context on public.messages (user_id, context, seq);`);
  L.push(`alter table public.${t.table} enable row level security;`);
  L.push(`drop policy if exists own_rows on public.${t.table};`);
  L.push(`create policy own_rows on public.${t.table} for all to authenticated\n  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));`);
  L.push(`revoke all on public.${t.table} from anon, authenticated;`);
  L.push(`grant select, insert, update on public.${t.table} to authenticated;`);
  L.push('');
}

L.push(`-- Invite list. Only emails listed here can create an account during the alpha.`);
L.push(`-- Add someone: insert into public.invites (email) values ('person@example.com');`);
L.push(`create table if not exists public.invites (\n  email text primary key,\n  note text not null default '',\n  invited_at timestamptz not null default now()\n);`);
L.push(`alter table public.invites enable row level security;`);
L.push(`revoke all on public.invites from anon, authenticated;`);
L.push('');
L.push(`create or replace function public.enforce_invite() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.invites i where lower(i.email) = lower(new.email)) then
    raise exception 'Life in Design is invite-only during the alpha.';
  end if;
  return new;
end;
$$;`);
L.push(`revoke all on function public.enforce_invite() from public, anon, authenticated;`);
L.push(`drop trigger if exists enforce_invite on auth.users;`);
L.push(`create trigger enforce_invite before insert on auth.users for each row execute function public.enforce_invite();`);
L.push('');

L.push(`-- Everything one person's request needs, in one call. Runs as the caller, so the own-rows rules apply.`);
const parts = Object.values(TABLES).map((t) => {
  const where = t.table === 'messages' ? `t.user_id = (select auth.uid()) and t.context = ctx` : `t.user_id = (select auth.uid())`;
  return `    '${t.table}', coalesce((select jsonb_agg(to_jsonb(t) - 'seq' - 'inserted_at' order by t.seq) from public.${t.table} t where ${where}), '[]'::jsonb)`;
});
L.push(`create or replace function public.my_snapshot(ctx text default '') returns jsonb
language sql stable security invoker set search_path = '' as $$
  select jsonb_build_object(
${parts.join(',\n')}
  );
$$;`);
L.push(`revoke all on function public.my_snapshot(text) from public, anon;`);
L.push(`grant execute on function public.my_snapshot(text) to authenticated;`);
L.push('');

const out = path.join(__dirname, '..', 'supabase', 'schema.sql');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, L.join('\n'));
console.log('wrote', path.relative(process.cwd(), out), Object.keys(TABLES).length, 'tables');
